export type CreativeCommonsGlyph = keyof typeof GLYPHS;

const GLYPH_SIZE = 30;
const GLYPH_GAP = 5;
// Breathing room around the glyphs so a glyph edge never sits exactly on the
// viewBox boundary, where sub-pixel rounding at small sizes can clip it.
const GLYPH_PAD = 1;

/**
 * Renders one or more CC glyphs side by side in a single SVG, e.g. the CC
 * circle followed by the "BY" person for a CC BY badge. The viewBox grows with
 * the number of glyphs, so size with `h-* w-auto` to keep the aspect ratio.
 */
export default function CreativeCommonsIcon({
  glyphs = ["cc"],
  ...props
}: SVGProps<SVGSVGElement> & { glyphs?: CreativeCommonsGlyph[] }) {
  const width = glyphs.length * GLYPH_SIZE + (glyphs.length - 1) * GLYPH_GAP;

  return (
    <svg
      viewBox={`${-GLYPH_PAD} ${-GLYPH_PAD} ${width + GLYPH_PAD * 2} ${GLYPH_SIZE + GLYPH_PAD * 2}`}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      {...props}
    >
      {glyphs.map((glyph, index) => (
        <path
          key={glyph}
          transform={`translate(${index * (GLYPH_SIZE + GLYPH_GAP)})`}
          fillRule="evenodd"
          clipRule="evenodd"
          d={GLYPHS[glyph]}
          fill="currentColor"
        />
      ))}
    </svg>
  );
}
