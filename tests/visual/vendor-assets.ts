// Vendors the Google Fonts URLs root.tsx requests (read from the source) so the
// visual suite runs offline. Rerun after changing that link:
// `node visual/vendor-assets.ts`. KaTeX is served from node_modules instead.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const FRONTEND = path.join(import.meta.dirname, "../../frontend");
const ASSETS = path.join(import.meta.dirname, "assets");
const FILES = path.join(ASSETS, "files");

// Google Fonts serves a different stylesheet per browser; ask as Chrome.
const USER_AGENT =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/147.0.0.0 Safari/537.36";

function sourceUrl(file: string, pattern: RegExp): string {
  const match = readFileSync(path.join(FRONTEND, file), "utf8").match(pattern);
  if (!match) throw new Error(`No URL matching ${pattern} in frontend/${file}`);
  return match[0];
}

const googleFonts = sourceUrl(
  "app/root.tsx",
  /https:\/\/fonts\.googleapis\.com\/css2\?[^"]+/,
);

type Manifest = Record<string, { file: string; contentType: string }>;
const manifest: Manifest = {};
const written: string[] = [];

async function fetchOk(url: string): Promise<Response> {
  const response = await fetch(url, { headers: { "user-agent": USER_AGENT } });
  if (!response.ok) throw new Error(`${response.status} for ${url}`);
  return response;
}

function write(file: string, contents: string | Buffer): void {
  mkdirSync(path.dirname(path.join(FILES, file)), { recursive: true });
  writeFileSync(path.join(FILES, file), contents);
  written.push(path.join(FILES, file));
}

async function download(url: string, contentType: string): Promise<string> {
  const response = await fetchOk(url);
  const { hostname, pathname } = new URL(url);
  // The Google stylesheet's path (/css2) has no extension.
  let file = path.join(hostname, pathname);
  if (contentType.startsWith("text/css") && !file.endsWith(".css")) {
    file += ".css";
  }
  write(file, Buffer.from(await response.arrayBuffer()));
  manifest[url] = { file, contentType };
  return file;
}

/** Downloads a stylesheet and the woff2 fonts it references (what Chromium uses). */
async function vendorStylesheet(url: string): Promise<void> {
  const file = await download(url, "text/css; charset=utf-8");
  const css = readFileSync(path.join(FILES, file), "utf8");
  const fonts = new Set(
    [...css.matchAll(/url\(\s*["']?([^"')]+\.woff2)["']?\s*\)/g)].map(
      ([, ref]) => new URL(ref, url).href,
    ),
  );
  for (const font of fonts) await download(font, "font/woff2");
}

// The OFL requires each family's copyright notice and the full license text
// with the fonts. The text is the same for every family, so it's included once.
async function oflText(families: string[]): Promise<string> {
  const LICENSE_START = "This Font Software is licensed";
  const files = await Promise.all(
    families.map(async (family) => {
      const dir = family.replace(/\s+/g, "").toLowerCase();
      const url = `https://raw.githubusercontent.com/google/fonts/main/ofl/${dir}/OFL.txt`;
      return (await (await fetchOk(url)).text()).replace(/\r/g, "");
    }),
  );
  const notices = files.map((text) => text.split(LICENSE_START)[0].trim());
  const license = LICENSE_START + files[0].split(LICENSE_START)[1];
  return `${notices.join("\n")}\n\n${license.trimEnd()}\n`;
}

rmSync(ASSETS, { recursive: true, force: true });

await vendorStylesheet(googleFonts);
const families = new URL(googleFonts).searchParams
  .getAll("family")
  .map((family) => family.split(":")[0]);
write(path.join("fonts.gstatic.com", "OFL.txt"), await oflText(families));

mkdirSync(ASSETS, { recursive: true });
for (const [file, contents] of [
  ["manifest.json", `${JSON.stringify(manifest, null, 2)}\n`],
  [
    "NOTICE.md",
    `Generated by \`node visual/vendor-assets.ts\`; don't edit by hand.

\`files/\` holds ${families.join(", ")} from Google Fonts, under the SIL Open Font License 1.1. The copyright notices and the license text are in \`files/fonts.gstatic.com/OFL.txt\`.
`,
  ],
] as const) {
  writeFileSync(path.join(ASSETS, file), contents);
  written.push(path.join(ASSETS, file));
}

// Refuse to finish if git would ignore anything written here: an ignored file
// passes locally but is missing in CI. Exit status 1 means nothing is ignored.
try {
  const ignored = execFileSync(
    "git",
    ["check-ignore", "--no-index", ...written],
    {
      cwd: import.meta.dirname,
      encoding: "utf8",
    },
  );
  throw new Error(`git ignores these vendored files:\n${ignored}`);
} catch (error) {
  if ((error as { status?: number }).status !== 1) throw error;
}

console.log(`Vendored ${Object.keys(manifest).length} URLs into ${ASSETS}`);
